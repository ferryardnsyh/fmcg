<?php

namespace App\Services\Concerns;

use App\Support\WmsPolicy;
use App\Validation\MasterInput;
use RuntimeException;

trait ManagesOpnameWorkflows
{
    private function insertOpnameSession(array $data, ?array $actor): array
    {
        $opnameNumber = 'OPN-' . date('Ymd') . '-' . str_pad(random_int(1, 999), 3, '0', STR_PAD_LEFT);

        $sessionData = [
            'opname_number'=> $opnameNumber,
            'opname_date'  => $data['opname_date'],
            'notes'        => trim(strip_tags((string) ($data['notes'] ?? ''))),
            'status'       => WmsPolicy::STATUS_DRAFT,
            'created_by'   => $actor['id'],
            'created_at'   => date('Y-m-d H:i:s'),
        ];

        $this->db->table('stock_opname_sessions')->insert($sessionData);

        $idOpname = (int)$this->db->insertID();

        $this->autoGenerateDetails($idOpname);

        return $this->makeSuccessResult('Sesi opname berhasil dibuat', null, ['id_opname' => $idOpname]);
    }

    private function autoGenerateDetails(int $idOpname): void
    {
        $products = $this->db->table('products p')
            ->select('p.id_product')
            ->where('p.status', WmsPolicy::STATUS_ACTIVE)
            ->get()
            ->getResultArray();

        foreach ($products as $product) {
            $batches = $this->db->table('product_batches pb')
                ->select('pb.id_batch, pb.quantity')
                ->where('pb.id_product', $product['id_product'])
                ->get()
                ->getResultArray();

            foreach ($batches as $batch) {
                $this->db->table('stock_opname_details')->insert([
                    'id_opname'        => $idOpname,
                    'id_batch'         => $batch['id_batch'],
                    'system_quantity'  => (int)$batch['quantity'],
                    'physical_quantity'=> 0,
                    'difference'       => 0,
                    'created_at'       => date('Y-m-d H:i:s'),
                ]);
            }
        }
    }

    private function rollbackOpnameWith(array $result): array
    {
        $this->db->transRollback();

        return $result;
    }

    private function lockOpnameSession($idOpname, string $statusMessage): array
    {
        $session = $this->db->query(
            'SELECT * FROM stock_opname_sessions WHERE id_opname = ? FOR UPDATE',
            [$idOpname]
        )->getRowArray();

        if (!$session) {
            return [null, $this->rollbackOpnameWith($this->makeFailureResult('Sesi opname tidak ditemukan'))];
        }

        if ($session['status'] !== WmsPolicy::STATUS_DRAFT) {
            return [null, $this->rollbackOpnameWith($this->makeFailureResult($statusMessage))];
        }

        return [$session, null];
    }

    private function lockOpnameBatch($batchId): array
    {
        $batch = $this->db->query(
            'SELECT * FROM product_batches WHERE id_batch = ? FOR UPDATE',
            [$batchId]
        )->getRowArray();

        if (!$batch) {
            return [null, $this->rollbackOpnameWith($this->makeFailureResult('Batch tidak ditemukan'))];
        }

        return [$batch, null];
    }

    private function saveOpnameDetail(array $data, array $batch, $session): array
    {
        $systemQuantity = (int)$batch['quantity'];
        $batchId = $batch['id_batch'];

        $physicalQuantity = MasterInput::parseInteger($data['physical_quantity'] ?? 0, 0, 2147483647);
        if ($physicalQuantity === null) {
            return $this->rollbackOpnameWith($this->makeFailureResult('Stok fisik harus bilangan bulat antara 0 dan 2147483647'));
        }
        $difference = $physicalQuantity - $systemQuantity;

        $detailData = [
            'id_opname'        => $data['id_opname'],
            'id_batch'         => $batchId,
            'system_quantity'  => $systemQuantity,
            'physical_quantity'=> $physicalQuantity,
            'difference'       => $difference,
        ];

        $existing = $this->db->query(
            'SELECT * FROM stock_opname_details WHERE id_opname = ? AND id_batch = ? FOR UPDATE',
            [$data['id_opname'], $batchId]
        )->getRowArray();

        if ($existing) {
            $this->db->table('stock_opname_details')
                ->where('id_opname_detail', $existing['id_opname_detail'])
                ->update($detailData);
            $detailId = $existing['id_opname_detail'];
        } else {
            $detailData['created_at'] = date('Y-m-d H:i:s');
            $this->db->table('stock_opname_details')->insert($detailData);
            $detailId = $this->db->insertID();
        }

        if (!$this->db->transCommit()) {
            throw new RuntimeException('Gagal menyimpan detail opname');
        }

        return $this->makeSuccessResult('Detail opname berhasil ditambahkan', null, [
            'id_opname_detail' => $detailId,
            'difference'       => $difference,
        ]);
    }

    private function lockOpnameCompletion(int $id): array
    {
        [$session, $error] = $this->lockOpnameSession($id, 'Sesi opname sudah selesai atau dibatalkan');
        if ($error !== null) {
            return [null, null, $error];
        }

        $details = $this->db->query(
            'SELECT * FROM stock_opname_details WHERE id_opname = ? FOR UPDATE',
            [$id]
        )->getResultArray();

        if (empty($details)) {
            return [null, null, $this->rollbackOpnameWith($this->makeFailureResult('Tidak ada detail opname untuk diselesaikan'))];
        }

        return [$session, $details, null];
    }

    private function applyOpnameCompletion(int $id, array $session, array $details): ?array
    {
        $seenBatchIds = [];

        foreach ($details as $detail) {
            $batchId = (int)($detail['id_batch'] ?? 0);
            if ($batchId === 0 || isset($seenBatchIds[$batchId])) {
                continue;
            }
            $seenBatchIds[$batchId] = true;

            $batch = $this->db->query(
                'SELECT * FROM product_batches WHERE id_batch = ? FOR UPDATE',
                [$batchId]
            )->getRowArray();

            if (!$batch) {
                return $this->rollbackOpnameWith($this->makeFailureResult('Batch opname tidak ditemukan'));
            }

            $systemQuantity = (int)$batch['quantity'];
            $physicalQuantity = (int)$detail['physical_quantity'];
            $difference = $physicalQuantity - $systemQuantity;

            $this->db->table('stock_opname_details')
                ->where('id_opname_detail', $detail['id_opname_detail'])
                ->update([
                    'system_quantity'  => $systemQuantity,
                    'physical_quantity'=> $physicalQuantity,
                    'difference'       => $difference,
                ]);

            if ($difference === 0) {
                continue;
            }

            $this->db->table('stock_adjustments')->insert([
                'id_batch'   => $batchId,
                'type'       => $difference > 0 ? WmsPolicy::TYPE_INCREASE : WmsPolicy::TYPE_DECREASE,
                'quantity'   => abs($difference),
                'reason'     => 'Stock Opname: ' . $session['opname_number'],
                'status'     => WmsPolicy::STATUS_PENDING,
                'created_by' => $session['created_by'],
                'created_at' => date('Y-m-d H:i:s'),
            ]);
        }

        $this->db->table('stock_opname_sessions')
            ->where('id_opname', $id)
            ->where('status', WmsPolicy::STATUS_DRAFT)
            ->update([
                'status' => WmsPolicy::STATUS_COMPLETED,
                'updated_at' => date('Y-m-d H:i:s')
            ]);

        if ($this->db->affectedRows() !== 1) {
            return $this->rollbackOpnameWith($this->makeFailureResult('Status opname berubah saat proses selesai', 409));
        }

        if (!$this->db->transCommit()) {
            throw new RuntimeException('Gagal menyimpan penyelesaian opname');
        }

        return $this->makeSuccessResult('Sesi opname berhasil diselesaikan. Adjustment menunggu persetujuan.');
    }
}
