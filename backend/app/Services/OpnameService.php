<?php

namespace App\Services;

use App\Validation\MasterInput;
use Config\Database;

class OpnameService
{
    protected $db;

    public function __construct()
    {
        $this->db = Database::connect();
    }

    public function createSession(array $data, ?array $actor = null): array
    {
        if ($actor === null) {
            return [
                'status' => false,
                'message' => 'Unauthorized'
            ];
        }

        if (empty($data['opname_date'])) {
            return [
                'status' => false,
                'message' => 'Tanggal opname wajib diisi'
            ];
        }

        if (!MasterInput::isValidIsoDate($data['opname_date'])) {
            return [
                'status' => false,
                'message' => 'Tanggal opname harus berformat YYYY-MM-DD'
            ];
        }

        $opnameNumber = 'OPN-' . date('Ymd') . '-' . str_pad(random_int(1, 999), 3, '0', STR_PAD_LEFT);

        $sessionData = [
            'opname_number'=> $opnameNumber,
            'opname_date'  => $data['opname_date'],
            'notes'        => trim(strip_tags((string) ($data['notes'] ?? ''))),
            'status'       => 'DRAFT',
            'created_by'   => $actor['id'],
            'created_at'   => date('Y-m-d H:i:s'),
        ];

        $this->db->transBegin();

        try {
            $this->db->table('stock_opname_sessions')->insert($sessionData);

            $idOpname = (int)$this->db->insertID();

            $this->autoGenerateDetails($idOpname);

            $this->db->transCommit();

            return [
                'status' => true,
                'message' => 'Sesi opname berhasil dibuat',
                'data' => ['id_opname' => $idOpname]
            ];
        } catch (\Throwable $e) {
            $this->db->transRollback();
            log_message('error', 'OpnameService::createSession: ' . $e->getMessage() . ' at ' . $e->getFile() . ':' . $e->getLine());

            return [
                'status' => false,
                'message' => 'Gagal membuat sesi opname'
            ];
        }
    }

    private function autoGenerateDetails(int $idOpname): void
    {
        $products = $this->db->table('products p')
            ->select('p.id_product')
            ->where('p.status', 'AKTIF')
            ->get()
            ->getResultArray();

        foreach ($products as $product) {
            $batches = $this->db->table('product_batches pb')
                ->select('pb.id_batch, pb.quantity')
                ->where('pb.id_product', $product['id_product'])
                ->get()
                ->getResultArray();

            foreach ($batches as $batch) {
                $this->db->table('stock_opname_details')->insert([
                    'id_opname'        => $idOpname,
                    'id_batch'         => $batch['id_batch'],
                    'system_quantity'  => (int)$batch['quantity'],
                    'physical_quantity'=> 0,
                    'difference'       => 0,
                    'created_at'       => date('Y-m-d H:i:s'),
                ]);
            }
        }
    }

    public function getAllSessions(): array
    {
        $sessions = $this->db
            ->table('stock_opname_sessions sos')
            ->select('
                sos.*,
                u.name AS created_by_name
            ')
            ->join('users u', 'u.id_user = sos.created_by', 'left')
            ->orderBy('sos.created_at', 'DESC')
            ->get()
            ->getResultArray();

        return [
            'status' => true,
            'data' => $sessions
        ];
    }

    public function getSessionById(int $id): array
    {
        $session = $this->db
            ->table('stock_opname_sessions sos')
            ->select('
                sos.*,
                u.name AS created_by_name
            ')
            ->join('users u', 'u.id_user = sos.created_by', 'left')
            ->where('sos.id_opname', $id)
            ->get()
            ->getRowArray();

        if (!$session) {
            return [
                'status' => false,
                'message' => 'Sesi opname tidak ditemukan'
            ];
        }

        $details = $this->db
            ->table('stock_opname_details sod')
            ->select('
                sod.*,
                p.name AS product_name,
                p.sku_code,
                pb.batch_number
            ')
            ->join('stock_opname_sessions sos', 'sod.id_opname = sos.id_opname', 'inner')
            ->join('product_batches pb', 'pb.id_batch = sod.id_batch', 'left')
            ->join('products p', 'p.id_product = pb.id_product', 'left')
            ->where('sod.id_opname', $session['id_opname'])
            ->get()
            ->getResultArray();

        $session['details'] = $details;

        return [
            'status' => true,
            'data' => $session
        ];
    }

    public function addDetail(array $data): array
    {
        if (empty($data['id_opname']) || empty($data['id_batch'])) {
            return [
                'status' => false,
                'message' => 'Opname ID dan Batch ID wajib diisi'
            ];
        }

        $this->db->transBegin();

        try {
            $session = $this->db->query(
                'SELECT * FROM stock_opname_sessions WHERE id_opname = ? FOR UPDATE',
                [$data['id_opname']]
            )->getRowArray();

            if (!$session) {
                $this->db->transRollback();
                return [
                    'status' => false,
                    'message' => 'Sesi opname tidak ditemukan'
                ];
            }

            if ($session['status'] !== 'DRAFT') {
                $this->db->transRollback();
                return [
                    'status' => false,
                    'message' => 'Hanya sesi dengan status DRAFT yang bisa ditambahkan detail'
                ];
            }

            $batch = $this->db->query(
                'SELECT * FROM product_batches WHERE id_batch = ? FOR UPDATE',
                [$data['id_batch']]
            )->getRowArray();

            if (!$batch) {
                $this->db->transRollback();
                return [
                    'status' => false,
                    'message' => 'Batch tidak ditemukan'
                ];
            }

            $systemQuantity = (int)$batch['quantity'];
            $batchId = $batch['id_batch'];

            $physicalQuantity = MasterInput::parseInteger($data['physical_quantity'] ?? 0, 0, 2147483647);
            if ($physicalQuantity === null) {
                $this->db->transRollback();
                return [
                    'status' => false,
                    'message' => 'Stok fisik harus bilangan bulat antara 0 dan 2147483647'
                ];
            }
            $difference = $physicalQuantity - $systemQuantity;

            $detailData = [
                'id_opname'        => $data['id_opname'],
                'id_batch'         => $batchId,
                'system_quantity'  => $systemQuantity,
                'physical_quantity'=> $physicalQuantity,
                'difference'       => $difference,
            ];

            $existing = $this->db->query(
                'SELECT * FROM stock_opname_details WHERE id_opname = ? AND id_batch = ? FOR UPDATE',
                [$data['id_opname'], $batchId]
            )->getRowArray();

            if ($existing) {
                $this->db->table('stock_opname_details')
                    ->where('id_opname_detail', $existing['id_opname_detail'])
                    ->update($detailData);
                $detailId = $existing['id_opname_detail'];
            } else {
                $detailData['created_at'] = date('Y-m-d H:i:s');
                $this->db->table('stock_opname_details')->insert($detailData);
                $detailId = $this->db->insertID();
            }

            if (!$this->db->transCommit()) {
                throw new \RuntimeException('Gagal menyimpan detail opname');
            }

            return [
                'status' => true,
                'message' => 'Detail opname berhasil ditambahkan',
                'data' => [
                    'id_opname_detail' => $detailId,
                    'difference' => $difference
                ]
            ];
        } catch (\Throwable $e) {
            $this->db->transRollback();
            log_message('error', 'OpnameService::addDetail: ' . $e->getMessage() . ' at ' . $e->getFile() . ':' . $e->getLine());

            return [
                'status' => false,
                'message' => 'Gagal menyimpan detail opname'
            ];
        }
    }

    public function completeSession(int $id): array
    {
        $this->db->transBegin();

        try {
            $sessionResult = $this->db->query(
                'SELECT * FROM stock_opname_sessions WHERE id_opname = ? FOR UPDATE',
                [$id]
            );
            $session = $sessionResult->getRowArray();

            if (!$session) {
                $this->db->transRollback();
                return [
                    'status' => false,
                    'message' => 'Sesi opname tidak ditemukan'
                ];
            }

            if ($session['status'] !== 'DRAFT') {
                $this->db->transRollback();
                return [
                    'status' => false,
                    'message' => 'Sesi opname sudah selesai atau dibatalkan'
                ];
            }

            $detailResult = $this->db->query(
                'SELECT * FROM stock_opname_details WHERE id_opname = ? FOR UPDATE',
                [$id]
            );
            $details = $detailResult->getResultArray();

            if (empty($details)) {
                $this->db->transRollback();
                return [
                    'status' => false,
                    'message' => 'Tidak ada detail opname untuk diselesaikan'
                ];
            }

            $seenBatchIds = [];

            foreach ($details as $detail) {
                $batchId = (int)($detail['id_batch'] ?? 0);
                if ($batchId === 0 || isset($seenBatchIds[$batchId])) {
                    continue;
                }
                $seenBatchIds[$batchId] = true;

                $batch = $this->db->query(
                    'SELECT * FROM product_batches WHERE id_batch = ? FOR UPDATE',
                    [$batchId]
                )->getRowArray();

                if (!$batch) {
                    $this->db->transRollback();
                    return [
                        'status' => false,
                        'message' => 'Batch opname tidak ditemukan'
                    ];
                }

                $systemQuantity = (int)$batch['quantity'];
                $physicalQuantity = (int)$detail['physical_quantity'];
                $difference = $physicalQuantity - $systemQuantity;

                $this->db->table('stock_opname_details')
                    ->where('id_opname_detail', $detail['id_opname_detail'])
                    ->update([
                        'system_quantity'  => $systemQuantity,
                        'physical_quantity'=> $physicalQuantity,
                        'difference'       => $difference,
                    ]);

                if ($difference === 0) {
                    continue;
                }

                $this->db->table('stock_adjustments')->insert([
                    'id_batch'   => $batchId,
                    'type'       => $difference > 0 ? 'INCREASE' : 'DECREASE',
                    'quantity'   => abs($difference),
                    'reason'     => 'Stock Opname: ' . $session['opname_number'],
                    'status'     => 'PENDING',
                    'created_by' => $session['created_by'],
                    'created_at' => date('Y-m-d H:i:s'),
                ]);
            }

            $this->db->table('stock_opname_sessions')
                ->where('id_opname', $id)
                ->where('status', 'DRAFT')
                ->update([
                    'status' => 'COMPLETED',
                    'updated_at' => date('Y-m-d H:i:s')
                ]);

            if ($this->db->affectedRows() !== 1) {
                $this->db->transRollback();
                return [
                    'status' => false,
                    'message' => 'Status opname berubah saat proses selesai',
                    'code'    => 409,
                ];
            }

            if (!$this->db->transCommit()) {
                throw new \RuntimeException('Gagal menyimpan penyelesaian opname');
            }

            return [
                'status' => true,
                'message' => 'Sesi opname berhasil diselesaikan. Adjustment menunggu persetujuan.'
            ];
        } catch (\Throwable $e) {
            $this->db->transRollback();
            log_message('error', 'OpnameService::completeSession: ' . $e->getMessage() . ' at ' . $e->getFile() . ':' . $e->getLine());

            return [
                'status' => false,
                'message' => 'Gagal menyelesaikan opname'
            ];
        }
    }

    public function deleteSession(int $id): array
    {
        $session = $this->db->table('stock_opname_sessions')
            ->where('id_opname', $id)
            ->get()
            ->getRowArray();

        if (!$session) {
            return [
                'status' => false,
                'message' => 'Sesi opname tidak ditemukan'
            ];
        }

        if ($session['status'] === 'COMPLETED') {
            return [
                'status' => false,
                'message' => 'Sesi opname yang sudah selesai tidak bisa dihapus'
            ];
        }

        $this->db->transBegin();

        try {
            $this->db->table('stock_opname_details')->where('id_opname', $id)->delete();
            $this->db->table('stock_opname_sessions')->where('id_opname', $id)->delete();

            $this->db->transCommit();

            return [
                'status' => true,
                'message' => 'Sesi opname berhasil dihapus'
            ];
        } catch (\Throwable $e) {
            $this->db->transRollback();
            log_message('error', 'OpnameService::deleteSession: ' . $e->getMessage() . ' at ' . $e->getFile() . ':' . $e->getLine());

            return [
                'status' => false,
                'message' => 'Gagal menghapus sesi opname'
            ];
        }
    }
}
